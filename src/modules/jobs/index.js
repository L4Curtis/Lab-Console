/**
 * Bench jobs module: backup, injection, reset, comparison with the live
 * devices; snapshots (list, read, diff, ZIP, import, search); TP templates
 * and the base configuration; the TP folder; the backup offered when a bench
 * is released (SPEC "Lot jobs")
 *
 * HTTP (/api/jobs), every route behind the sign-in gate:
 *   GET  /benches/:bench                 devices (shared ones marked, admin switches never), people on
 *                                        their consoles, the job running, the base configuration, the
 *                                        backup offer of a release, what this user may do
 *   POST /benches/:bench/backup          { devices?, label?, enablePasswords?, linePasswords? }
 *   POST /benches/:bench/reset           { devices, confirm: '<bench>', forceErase?, applyBase?, save?, … }   starts after a countdown
 *   POST /benches/:bench/preview         { source: { snapshot | template }, devices?, rsaModulus? } → each device's exact script
 *   POST /benches/:bench/inject          { source, devices?, mode: 'reset' | 'merge', save?, rsaModulus?, scripts: { key: sha256 }, confirm? }
 *   POST /benches/:bench/compare         { snapshot, devices? }   a snapshot against the live devices
 *   GET  /benches/:bench/folder?snapshot=  the TP folder: final configurations and console journals, one ZIP
 *   GET  /runs?bench= · GET /runs/:id · POST /runs/:id/cancel
 *   GET  /snapshots?bench= · GET /snapshots/search?q= · GET /snapshots/:id · GET /snapshots/:id/devices/:device[?vlans=1]
 *   GET  /snapshots/:id/zip · GET /snapshots/:a/diff/:b[?device=] · POST /snapshots/import?bench=&label= (a ZIP) · DELETE /snapshots/:id
 *   GET  /templates · GET /templates/:id · GET /templates/:id/devices/:device
 *   POST /templates { name, description, snapshot?, devices?, configs? } · POST /templates/import?name=&description= (a ZIP)
 *   PUT  /templates/:id { name?, description?, base? } · DELETE /templates/:id          (templates: admins write, everyone reads)
 *
 * Who may run a job: services.benches.canOperate(user, bench) (the occupants
 * of an unlocked bench, and admins); after a release, the team that released
 * may still back the bench up for a while (the offer). One job per bench, and
 * none while a bench check runs (services.checks.running).
 * SSE: 'jobs:running' (sticky, everyone: which bench runs what, device by
 * device), 'jobs:job' (the job, to those who may see it), 'jobs:done' (once
 * per finished job, to the bench's occupants: { bench, jobId, kind, ok, state }).
 *
 * Seeing a job is decided by what was true when it ran, never by who holds
 * the bench now: the members of the team that held it (job.teamId) and the
 * admins read the whole report, which carries configuration lines (diffs,
 * refused commands, console output). Its actor, when not one of them, and
 * the bench's occupants while the job runs, see it without those lines
 * (redactedJob); nobody else sees it.
 */
import fs from 'node:fs';
import express from 'express';
import { httpError } from '../../lib/httpError.js';
import { dayOf } from '../consoles/journal.js';
import { Library, templateView } from './library.js';
import { JobRunner, scaledTimeouts, planScript, publicJob, redactedJob } from './runner.js';
import { makeZip, vlanText, ANY_DEVICE } from './configFiles.js';

const OFFER_MS = 30 * 60_000;
/** Why toReplayScript drops a line (its English reason) → the code the browser translates (jobs.dropped.*) */
const DROPPED = {
  'set by the software image': 'version',
  'boot marker': 'boot_marker',
  'licence: tied to the chassis, not replayable': 'licence',
  'factory default of IOS XE': 'xe_default',
  'certificate: generated by the device itself': 'certificate',
  'computed by the device': 'computed',
  'factory default (Smart Licensing)': 'smart_licensing',
  'system policy of IOS XE': 'xe_policy',
  'banner text uses every possible delimiter': 'banner',
};
const RSA_MODULI = [512, 768, 1024, 2048, 4096];
const KINDS = ['backup', 'reset', 'inject', 'compare'];
const MUTATING = new Set(['reset', 'inject']);
const LIVE = new Set(['pending', 'running']);

const isAdmin = (u) => u?.role === 'admin';
const targetKey = (t) => `${t.host}:${t.port}`;

/**
 * @param options  test seam: { timeouts (driver budgets), pacing (script typing), countdownMs, devicesAtOnce, now }
 */
export function createJobsModule({ config, logger, events, store, repos, audit, infra, services }, options = {}) {
  const log = logger.child('jobs');
  const cfg = config.jobs ?? { devicesAtOnce: 5, countdownSeconds: 10, importMaxKb: 2048, timeScale: 1 };
  const now = options.now ?? (() => Date.now());
  const library = new Library({ store, repos, services, audit, now });
  const offers = new Map(); // bench → { teamId, until }: the backup offered after a release

  // ── Who may do what ───────────────────────────────────────────────────────

  const benches = () => services.benches;
  const teamOf = (user) => services.teams?.teamOf?.(user) ?? null;
  const isMember = (user, teamId) => Boolean(teamId && services.teams?.get?.(teamId)?.members?.includes(user?.id));

  /** The backup a release offered to this user's team, while it holds (bench still free, or theirs, and not locked) */
  function offerFor(user, bench) {
    const offer = offers.get(bench);
    if (!offer || offer.until < now()) return null;
    if (!isMember(user, offer.teamId)) return null;
    const holder = benches()?.holder?.(bench);
    if (benches()?.lock?.(bench) || (holder && holder.teamId !== offer.teamId)) return null;
    return offer;
  }

  /** Why `user` may not run a job on `bench` (an HttpError), or null */
  function refusal(user, bench, { offerOk = false } = {}) {
    if (benches()?.canOperate?.(user, bench)) return null;
    const lock = benches()?.lock?.(bench);
    if (lock) return httpError(423, 'jobs.locked', 'This bench is locked: nobody but admins runs jobs on it.', { reason: lock.reason });
    if (offerOk && offerFor(user, bench)) return null;
    return httpError(403, 'jobs.not_occupant', 'Only the occupants of this bench (and admins) run jobs on it.', { bench });
  }

  /** A job goes on device after device only while its actor may still run it (and, erasing or writing, touch a shared line) */
  function mayGoOn(job, device) {
    const user = job.hidden.actorUser;
    if (MUTATING.has(job.kind) && device?.shared && sharedConflict(user, job.bench, [device])) return false;
    if (isAdmin(user)) return true;
    if (benches()?.canOperate?.(user, job.bench)) return true;
    return Boolean(job.options.offer && offerFor(user, job.bench));
  }

  /**
   * What `user` may see of `job`: 'full' (the members of the team that held
   * the bench when it ran, admins), 'summary' (its actor otherwise; the
   * bench's occupants while it runs, or in its own publications), or null
   */
  function viewOf(user, job, { live = false } = {}) {
    if (!user?.id) return null;
    if (isAdmin(user) || library.canSee(user, { teamId: job.teamId })) return 'full';
    if (job.actor?.id === user.id) return 'summary';
    if ((live || LIVE.has(job.state)) && benches()?.isOccupant?.(user, job.bench)) return 'summary';
    return null;
  }

  /** The job as `user` may see it, or null */
  function jobFor(user, job, options) {
    const view = viewOf(user, job, options);
    if (view === 'full') return job.hidden ? publicJob(job) : job;
    if (view === 'summary') return redactedJob(job);
    return null;
  }

  const runner = new JobRunner({
    services, events, audit, repos, library, logger: log, viewOf, mayGoOn,
    options: {
      devicesAtOnce: options.devicesAtOnce ?? cfg.devicesAtOnce,
      countdownMs: options.countdownMs ?? cfg.countdownSeconds * 1000,
      timeouts: options.timeouts ?? scaledTimeouts(cfg.timeScale),
      pacing: options.pacing,
      now,
    },
  });

  // ── Benches and devices ───────────────────────────────────────────────────

  function lab(name) {
    const found = services.consoles?.registry?.model?.labs?.find((l) => l.name === name);
    if (!found) throw httpError(404, 'jobs.unknown_bench', 'This bench does not exist.', { bench: String(name ?? '').slice(0, 40) });
    return found;
  }

  /** The bench's devices a job may touch: never an admin switch; shared ones marked */
  function devicesOf(bench) {
    const admin = new Set((infra?.adminSwitches ?? []).map((s) => targetKey(s.target)));
    const shared = services.consoles?.sharedTargets?.() ?? new Set();
    const registry = services.consoles?.registry;
    return lab(bench).devices
      .filter((d) => d.target && !admin.has(targetKey(d.target)))
      // The registry's own device (with its bench): what the consoles open, journal and decide on
      .map((d) => ({ ...(registry?.getDevice?.(d.key) ?? d), labName: bench, shared: shared.has(targetKey(d.target)) }));
  }

  /**
   * A shared device erased or written while another bench using its line is
   * not free, or held by another team, or locked: the refusal, or null. Admins
   * are never refused
   */
  function sharedConflict(user, bench, devices) {
    if (isAdmin(user)) return null;
    const mine = teamOf(user)?.id ?? null;
    const labs = services.consoles?.registry?.model?.labs ?? [];
    for (const d of devices.filter((x) => x.shared)) {
      const key = targetKey(d.target);
      for (const other of labs) {
        if (other.name === bench || !other.devices?.some((x) => x.target && targetKey(x.target) === key)) continue;
        const holder = benches()?.holder?.(other.name);
        if (benches()?.lock?.(other.name) || (holder && holder.teamId !== mine)) {
          return httpError(409, 'jobs.shared_in_use', 'This device shares its console line with a bench another team holds: it is left alone.', { device: d.name, bench: other.name });
        }
      }
    }
    return null;
  }

  /** The devices asked for (keys), all of them of this bench; by default every device not shared with another bench */
  function pick(bench, keys) {
    const all = devicesOf(bench);
    if (keys === undefined || keys === null) return all.filter((d) => !d.shared);
    if (!Array.isArray(keys) || keys.length > 100 || keys.some((k) => typeof k !== 'string')) throw httpError(400, 'jobs.bad_devices', 'Devices are given as a list of keys.');
    const chosen = all.filter((d) => keys.includes(d.key));
    if (chosen.length !== new Set(keys).size) throw httpError(400, 'jobs.unknown_device', 'One of these devices is not on this bench.');
    if (!chosen.length) throw httpError(400, 'jobs.no_devices', 'Choose at least one device.');
    return chosen;
  }

  const secrets = (body) => ({ enablePasswords: list(body?.enablePasswords), linePasswords: list(body?.linePasswords) });
  function list(v) {
    if (v === undefined || v === null || v === '') return [];
    const arr = Array.isArray(v) ? v : [v];
    if (arr.length > 3 || arr.some((p) => typeof p !== 'string' || p.length > 64)) throw httpError(400, 'jobs.bad_passwords', 'At most three passwords of 64 characters.');
    return arr.filter((p) => p.length);
  }

  /** Start a job, or the refusal as an HttpError */
  function start(req, res, spec) {
    // A check reads the devices of the bench one after the other: nothing writes to them meanwhile
    const check = services.checks?.running?.(spec.bench);
    if (check) throw httpError(409, 'jobs.check_running', 'A check is running on this bench: wait until it ends.', { kind: check.kind, name: check.actor.name });
    const holder = benches()?.holder?.(spec.bench);
    const offer = !holder && spec.kind === 'backup' && !benches()?.canOperate?.(req.user, spec.bench) ? offerFor(req.user, spec.bench) : null;
    const { job, refused } = runner.start({
      ...spec,
      actor: req.user,
      teamId: holder?.teamId ?? offer?.teamId ?? null,
      options: { ...spec.options, ...(offer ? { offer: true } : {}) },
    });
    if (refused) throw httpError(refused.status, refused.code, refused.message, refused.params);
    res.status(202).json({ job: publicJob(job) });
  }

  // ── Sources of an injection, and the exact scripts ────────────────────────

  async function source(user, src) {
    if (src?.snapshot !== undefined) {
      const set = await library.snapshot(user, String(src.snapshot));
      return { set, kind: 'snapshot', id: set.id, name: set.label || set.id, fallback: false };
    }
    if (src?.template !== undefined) {
      const set = await library.template(String(src.template));
      return { set, kind: 'template', id: set.id, name: set.name, fallback: true };
    }
    throw httpError(400, 'jobs.no_source', 'Choose a snapshot or a template to inject.');
  }

  /** Per device: the script it will receive (what the preview shows and the job sends) */
  async function plan(user, bench, body) {
    const src = await source(user, body?.source);
    const rsaModulus = body?.rsaModulus === undefined || body?.rsaModulus === null || body?.rsaModulus === '' ? null : Number(body.rsaModulus);
    if (rsaModulus !== null && !RSA_MODULI.includes(rsaModulus)) throw httpError(400, 'jobs.bad_rsa', 'RSA keys: 512, 768, 1024, 2048 or 4096 bits.');
    const devices = pick(bench, body?.devices);
    const plans = new Map();
    const missing = [];
    for (const d of devices) {
      const entry = await library.readDevice(src.set, d.name, { fallback: src.fallback });
      if (!entry) { missing.push({ key: d.key, name: d.name, reason: 'absent' }); continue; }
      if (!entry.intact) { missing.push({ key: d.key, name: d.name, reason: 'damaged' }); continue; }
      const p = planScript(entry, { rsaModulus });
      plans.set(d.key, { ...p, from: entry.row.device === ANY_DEVICE ? `${src.name} (*)` : `${src.name}/${entry.row.device}`, source: { config: entry.config, vlans: entry.vlans } });
    }
    return { src, devices, plans, missing, rsaModulus };
  }

  // ── HTTP ──────────────────────────────────────────────────────────────────

  const router = express.Router();
  const json = express.json({ limit: '64kb' });
  const bigJson = express.json({ limit: '2mb' });
  const zipBody = express.raw({ type: () => true, limit: `${cfg.importMaxKb}kb` });
  const noStore = (res) => res.set('Cache-Control', 'no-store');

  router.get('/benches/:bench', async (req, res) => {
    const bench = lab(req.params.bench).name;
    const rooms = services.consoles?.rooms;
    const running = runner.running(bench);
    const base = await library.base();
    const holder = benches()?.holder?.(bench) ?? null;
    const offer = offerFor(req.user, bench);
    noStore(res).json({
      bench,
      canOperate: Boolean(benches()?.canOperate?.(req.user, bench)),
      lock: benches()?.lock?.(bench) ?? null,
      holder: holder ? { teamId: holder.teamId, teamName: library.teamName(holder.teamId) } : null,
      team: teamOf(req.user) ? { id: teamOf(req.user).id, name: teamOf(req.user).name } : null,
      offer: offer ? { until: new Date(offer.until).toISOString() } : null,
      devices: devicesOf(bench).map((d) => {
        const room = rooms?.get(targetKey(d.target));
        const summary = room?.summary();
        return { key: d.key, name: d.name, shared: d.shared, open: Boolean(room), people: summary?.users?.map((u) => u.name) ?? [], pilot: summary?.pilot?.name ?? null };
      }),
      running: running ? (jobFor(req.user, running) ?? runner.summary().jobs.find((j) => j.id === running.id)) : null,
      base: base ? { id: base.id, name: base.name } : null,
      countdownSeconds: Math.round(runner.countdownMs / 1000),
    });
  });

  router.post('/benches/:bench/backup', json, (req, res) => {
    const bench = lab(req.params.bench).name;
    const no = refusal(req.user, bench, { offerOk: true });
    if (no) throw no;
    const label = typeof req.body?.label === 'string' ? req.body.label.trim().slice(0, 80) : '';
    start(req, res, { kind: 'backup', bench, devices: pick(bench, req.body?.devices), secrets: secrets(req.body), options: { label } });
  });

  router.post('/benches/:bench/reset', json, async (req, res) => {
    const bench = lab(req.params.bench).name;
    const no = refusal(req.user, bench);
    if (no) throw no;
    if (req.body?.confirm !== bench) throw httpError(400, 'jobs.confirm_bench', 'Type the name of the bench to confirm the reset.', { bench });
    const devices = pick(bench, req.body?.devices);
    const shared = sharedConflict(req.user, bench, devices);
    if (shared) throw shared;
    const forceErase = Array.isArray(req.body?.forceErase) ? req.body.forceErase.filter((k) => typeof k === 'string') : [];
    if (forceErase.length && !isAdmin(req.user)) throw httpError(403, 'jobs.force_admin_only', 'Only an admin may erase a device whose backup failed.');
    if (forceErase.some((k) => !devices.some((d) => d.key === k))) throw httpError(400, 'jobs.unknown_device', 'One of these devices is not on this bench.');
    const base = req.body?.applyBase === false ? null : await library.base();
    start(req, res, {
      kind: 'reset', bench, devices, secrets: secrets(req.body), countdown: true,
      options: { forceErase, base, save: req.body?.save !== false, label: 'reset' },
    });
  });

  router.post('/benches/:bench/preview', json, async (req, res) => {
    const bench = lab(req.params.bench).name;
    const p = await plan(req.user, bench, req.body);
    noStore(res).json({
      source: { kind: p.src.kind, id: p.src.id, name: p.src.name },
      rsaModulus: p.rsaModulus,
      devices: p.devices.filter((d) => p.plans.has(d.key)).map((d) => {
        const x = p.plans.get(d.key);
        const dropped = x.dropped.map((r) => ({ ...r, code: DROPPED[r.reason] ?? 'other' }));
        return { key: d.key, name: d.name, shared: d.shared, from: x.from, script: x.script, sha256: x.sha256, lines: x.script.split('\n').length - 1, dropped, vlans: x.vlans };
      }),
      missing: p.missing,
    });
  });

  router.post('/benches/:bench/inject', json, async (req, res) => {
    const bench = lab(req.params.bench).name;
    const no = refusal(req.user, bench);
    if (no) throw no;
    const mode = req.body?.mode ?? 'reset';
    if (!['reset', 'merge'].includes(mode)) throw httpError(400, 'jobs.bad_mode', 'The mode is "reset" (then inject) or "merge".');
    if (mode === 'reset' && req.body?.confirm !== bench) throw httpError(400, 'jobs.confirm_bench', 'Type the name of the bench to confirm: its devices are erased first.', { bench });
    const p = await plan(req.user, bench, req.body);
    const shared = sharedConflict(req.user, bench, p.devices);
    if (shared) throw shared;
    if (p.missing.length) throw httpError(400, 'jobs.not_in_source', 'Some devices have no configuration in this source.', { devices: p.missing.map((m) => m.name).join(', ') });
    const seen = req.body?.scripts && typeof req.body.scripts === 'object' ? req.body.scripts : {};
    const stale = p.devices.filter((d) => seen[d.key] !== p.plans.get(d.key).sha256);
    if (stale.length) throw httpError(409, 'jobs.preview_stale', 'Look at the preview again: what would be sent is not what you saw.', { devices: stale.map((d) => d.name).join(', ') });
    start(req, res, {
      kind: 'inject', bench, devices: p.devices, secrets: secrets(req.body),
      options: { mode, save: req.body?.save !== false, plans: p.plans, rsaModulus: p.rsaModulus, source: { kind: p.src.kind, id: p.src.id, name: p.src.name }, label: `inject ${p.src.name}`.slice(0, 80) },
    });
  });

  router.post('/benches/:bench/compare', json, async (req, res) => {
    const bench = lab(req.params.bench).name;
    const no = refusal(req.user, bench);
    if (no) throw no;
    const set = await library.snapshot(req.user, String(req.body?.snapshot ?? ''));
    start(req, res, { kind: 'compare', bench, devices: pick(bench, req.body?.devices), secrets: secrets(req.body), options: { compareWith: set } });
  });

  // The TP folder: the configurations of a snapshot and the console journals of its day
  router.get('/benches/:bench/folder', async (req, res) => {
    const bench = lab(req.params.bench).name;
    const set = await library.snapshot(req.user, String(req.query.snapshot ?? ''));
    if (set.bench !== bench) throw httpError(400, 'jobs.other_bench', 'This snapshot is of another bench.');
    const day = dayOf(Date.parse(set.createdAt));
    const root = `TP-${store.safeName(bench)}-${day}`;
    const entries = {};
    for (const row of set.devices) {
      const d = await library.readDevice(set, row.device);
      entries[`${root}/configurations/${row.file}`] = d.config;
      if (row.vlanFile) entries[`${root}/configurations/${row.vlanFile}`] = vlanText(d.vlans ?? []);
      if (row.startupFile) {
        const startup = await library.readStartup(set, row).catch(() => null);
        if (startup) entries[`${root}/configurations/${row.startupFile}`] = startup.text;
      }
    }
    const journal = services.consoles?.journal;
    const teamOfUser = (u) => teamOf(u)?.id ?? null;
    const read = [];
    if (journal) {
      const days = (await journal.list()).filter((j) => j.bench === bench && j.day === day);
      for (const j of days) {
        if (!journal.canReadDay(req.user, journal.dayMetas(j.benchDir, j.deviceDir, j.day), teamOfUser)) continue;
        const { log: file } = journal.paths(j.benchDir, j.deviceDir, j.day, j.session);
        try {
          entries[`${root}/journals/${j.deviceDir}/${j.day}-${j.session}.log`] = new Uint8Array(await fs.promises.readFile(file));
          read.push(`${j.device} ${j.session}`);
        } catch { /* swept meanwhile */ }
      }
    }
    entries[`${root}/README.txt`] = `Lab Console - ${bench} - ${day}\nSnapshot ${set.id}${set.label ? ` (${set.label})` : ''}, ${set.createdAt}\n`
      + `configurations/: one running-config per device (and its startup-config when it was another)\njournals/: what the consoles printed that day (${read.length} sessions)\n`;
    audit.log(req, 'job.folder.download', { bench, snapshot: set.id, journals: read.length });
    sendZip(res, makeZip(entries), `${root}.zip`);
  });

  // ── Jobs ──────────────────────────────────────────────────────────────────

  async function jobOf(user, id) {
    if (typeof id !== 'string' || !/^[0-9a-f-]{36}$/.test(id)) throw httpError(404, 'jobs.no_job', 'There is no such job.');
    const job = runner.get(id) ?? await repos.jobs.get(id);
    if (!job) throw httpError(404, 'jobs.no_job', 'There is no such job.');
    const view = jobFor(user, job);
    if (!view) throw httpError(403, 'jobs.job_forbidden', 'This job belongs to another team.');
    return { job, view };
  }

  router.get('/runs', async (req, res) => {
    const bench = req.query.bench === undefined ? undefined : lab(String(req.query.bench)).name;
    const stored = await repos.jobs.list({ bench, limit: 50 });
    const live = new Map(runner.recent(bench).map((j) => [j.id, j]));
    const all = [...live.values(), ...stored.filter((j) => !live.has(j.id))].map((j) => jobFor(req.user, j)).filter(Boolean)
      .sort((a, b) => b.createdAt.localeCompare(a.createdAt)).slice(0, 50);
    noStore(res).json({ jobs: all.map((j) => ({ ...j, devices: j.devices.map(({ lastOutput: _output, ...d }) => d) })) });
  });

  router.get('/runs/:id', async (req, res) => {
    const { view } = await jobOf(req.user, req.params.id);
    noStore(res).json({ job: view });
  });

  router.post('/runs/:id/cancel', async (req, res) => {
    const { job } = await jobOf(req.user, req.params.id);
    const live = runner.get(job.id);
    if (!live || !['pending', 'running'].includes(live.state)) throw httpError(409, 'jobs.not_running', 'This job is over.');
    if (!(isAdmin(req.user) || live.actor.id === req.user.id || benches()?.canOperate?.(req.user, live.bench))) {
      throw httpError(403, 'jobs.cancel_forbidden', 'Only the person who started the job, the occupants of the bench and admins may stop it.');
    }
    runner.cancel(live, req.user);
    res.json({ job: jobFor(req.user, live, { live: true }) });
  });

  // ── Snapshots ─────────────────────────────────────────────────────────────

  router.get('/snapshots', async (req, res) => {
    const bench = req.query.bench === undefined ? undefined : lab(String(req.query.bench)).name;
    noStore(res).json({ snapshots: (await library.listSnapshots(req.user, { bench })).map((s) => library.view(s)) });
  });

  router.get('/snapshots/search', async (req, res) => {
    const q = typeof req.query.q === 'string' ? req.query.q.trim() : '';
    if (q.length < 2 || q.length > 100) throw httpError(400, 'jobs.bad_search', 'Search for 2 to 100 characters.');
    noStore(res).json(await library.search(req.user, q));
  });

  router.post('/snapshots/import', zipBody, async (req, res) => {
    const bench = lab(String(req.query.bench ?? '')).name;
    const label = typeof req.query.label === 'string' ? req.query.label.trim().slice(0, 80) : '';
    const { snapshot, ignored } = await library.importZip(req.user, bench, Buffer.isBuffer(req.body) ? req.body : Buffer.alloc(0), {
      label, devices: devicesOf(bench).map((d) => d.name), maxBytes: cfg.importMaxKb * 1024,
    });
    res.status(201).json({ snapshot: library.view(snapshot), ignored });
  });

  router.get('/snapshots/:id', async (req, res) => {
    noStore(res).json({ snapshot: library.view(await library.snapshot(req.user, req.params.id)) });
  });

  router.get('/snapshots/:id/devices/:device', async (req, res) => {
    const set = await library.snapshot(req.user, req.params.id);
    const d = await library.readDevice(set, req.params.device);
    if (!d) throw httpError(404, 'jobs.no_device', 'This device is not in the snapshot.');
    const startup = await library.readStartup(set, d.row).catch(() => null);
    noStore(res).json({ device: d.row.device, config: d.config, vlans: d.vlans, facts: d.facts, intact: d.intact, sha256: d.row.sha256, startup: startup?.text ?? null });
  });

  router.get('/snapshots/:id/zip', async (req, res) => {
    const set = await library.snapshot(req.user, req.params.id);
    const root = `${store.safeName(set.bench)}-${set.id}`;
    audit.log(req, 'job.snapshot.download', { bench: set.bench, snapshot: set.id });
    sendZip(res, await library.files.zip(set.dir, root), `${root}.zip`);
  });

  router.get('/snapshots/:a/diff/:b', async (req, res) => {
    const a = await library.snapshot(req.user, req.params.a);
    const b = await library.snapshot(req.user, req.params.b);
    const device = typeof req.query.device === 'string' ? req.query.device : undefined;
    noStore(res).json({ a: library.view(a), b: library.view(b), devices: await library.diff(a, b, { device }) });
  });

  router.delete('/snapshots/:id', async (req, res) => {
    await library.removeSnapshot(req.user, req.params.id);
    res.json({ ok: true });
  });

  // ── Templates: everyone reads, admins write ───────────────────────────────

  router.get('/templates', async (_req, res) => {
    noStore(res).json({ templates: (await library.templates()).map(templateView) });
  });

  router.get('/templates/:id', async (req, res) => {
    noStore(res).json({ template: templateView(await library.template(req.params.id)) });
  });

  router.get('/templates/:id/devices/:device', async (req, res) => {
    const t = await library.template(req.params.id);
    const d = await library.readDevice(t, req.params.device);
    if (!d) throw httpError(404, 'jobs.no_device', 'This device is not in the template.');
    noStore(res).json({ device: d.row.device, config: d.config, vlans: d.vlans, facts: d.facts, intact: d.intact });
  });

  const adminOnly = (req) => {
    if (!isAdmin(req.user)) throw httpError(403, 'auth.forbidden', 'Only admins publish templates.', { role: 'admin' });
  };

  router.post('/templates', bigJson, async (req, res) => {
    adminOnly(req);
    const { name, description, snapshot, devices, configs, base } = req.body ?? {};
    let entries;
    let from = null;
    if (snapshot !== undefined) {
      const set = await library.snapshot(req.user, String(snapshot));
      entries = await library.snapshotEntries(set, Array.isArray(devices) ? devices.filter((d) => typeof d === 'string') : null);
      from = set.id;
    } else {
      entries = library.typedEntries(configs);
    }
    let t = await library.publishTemplate(req.user, { name, description, entries, source: from });
    if (base === true) t = await library.updateTemplate(req.user, t.id, { base: true });
    res.status(201).json({ template: templateView(t) });
  });

  router.post('/templates/import', zipBody, async (req, res) => {
    adminOnly(req);
    const entries = library.zipEntries(Buffer.isBuffer(req.body) ? req.body : Buffer.alloc(0), cfg.importMaxKb * 1024);
    const t = await library.publishTemplate(req.user, { name: req.query.name, description: typeof req.query.description === 'string' ? req.query.description : '', entries, source: 'import' });
    res.status(201).json({ template: templateView(t) });
  });

  router.put('/templates/:id', json, async (req, res) => {
    adminOnly(req);
    const { name, description, base } = req.body ?? {};
    if (base !== undefined && typeof base !== 'boolean') throw httpError(400, 'jobs.bad_template', 'base is true or false.');
    res.json({ template: templateView(await library.updateTemplate(req.user, req.params.id, { name, description, base })) });
  });

  router.delete('/templates/:id', async (req, res) => {
    adminOnly(req);
    await library.removeTemplate(req.user, req.params.id);
    res.json({ ok: true });
  });

  function sendZip(res, data, filename) {
    res.set({
      'Cache-Control': 'no-store',
      'Content-Type': 'application/zip',
      'Content-Disposition': `attachment; filename="${filename.replace(/[^\w.-]/g, '_')}"`,
      'X-Content-Type-Options': 'nosniff',
    });
    res.end(Buffer.from(data));
  }

  // ── Published for the other modules ───────────────────────────────────────

  services.jobs = {
    /** The job holding a bench (pending or running), as everyone may see it, or null */
    running: (labName) => runner.summary().jobs.find((j) => j.bench === labName) ?? null,
    /** Recent jobs (in memory), newest first, without a line of configuration (redactedJob) */
    list: ({ bench } = {}) => runner.recent(bench).map(redactedJob),
    kinds: KINDS,
  };

  let offRelease = null;
  return {
    id: 'jobs',
    title: 'Bench jobs',
    enabled: true,
    router,
    runner,
    library,
    offers,
    async start() {
      // Jobs a stopped server left behind: they did not finish, say so
      for (const job of await repos.jobs.unfinished()) {
        const devices = job.devices.map((d) => (['queued', 'waiting', 'running'].includes(d.state) ? { ...d, state: 'failed', code: 'jobs.interrupted', step: null } : d));
        await repos.jobs.save({ ...job, state: 'failed', devices, endedAt: new Date(now()).toISOString() });
      }
      events.publish('jobs:running', runner.summary(), { sticky: true });
      // A release offers a backup to the team that let the bench go
      offRelease = benches()?.onRelease?.(({ labName, teamId }) => {
        if (!teamId) return null;
        offers.set(labName, { teamId, until: now() + OFFER_MS });
        return { kind: 'backup', bench: labName, href: `#/jobs/${encodeURIComponent(labName)}/backup` };
      }) ?? null;
    },
    shutdown() {
      offRelease?.();
      runner.shutdown();
    },
  };
}

