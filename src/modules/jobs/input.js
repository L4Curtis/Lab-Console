/**
 * What a job request may carry, checked: the devices asked for, the
 * passwords to try, the RSA modulus of an injection; and the ZIP answers
 */
import { httpError } from '../../lib/httpError.js';

const RSA_MODULI = [512, 768, 1024, 2048, 4096];
const CONTROL = /[\x00-\x1f\x7f]/;

/** Why toReplayScript drops a line (its English reason) → the code the browser translates (jobs.dropped.*) */
const DROPPED = {
  'set by the software image': 'version',
  'boot marker': 'boot_marker',
  'licence: tied to the chassis, not replayable': 'licence',
  'factory default of IOS XE': 'xe_default',
  'certificate: generated by the device itself': 'certificate',
  'computed by the device': 'computed',
  'factory default (Smart Licensing)': 'smart_licensing',
  'system policy of IOS XE': 'xe_policy',
  'banner text uses every possible delimiter': 'banner',
};
export const droppedCode = (reason) => DROPPED[reason] ?? 'other';

/**
 * The devices asked for (keys) among `all` (a bench's task devices); by
 * default every device not shared with another bench
 */
export function pickDevices(all, keys) {
  if (keys === undefined || keys === null) return all.filter((d) => !d.shared);
  if (!Array.isArray(keys) || keys.length > 100 || keys.some((k) => typeof k !== 'string')) throw httpError(400, 'jobs.bad_devices', 'Devices are given as a list of keys.');
  const chosen = all.filter((d) => keys.includes(d.key));
  if (chosen.length !== new Set(keys).size) throw httpError(400, 'jobs.unknown_device', 'One of these devices is not on this bench.');
  if (!chosen.length) throw httpError(400, 'jobs.no_devices', 'Choose at least one device.');
  return chosen;
}

/** The passwords a job tries on the devices (memory only, never recorded) */
export const secretsOf = (body) => ({ enablePasswords: passwords(body?.enablePasswords), linePasswords: passwords(body?.linePasswords) });

function passwords(v) {
  if (v === undefined || v === null || v === '') return [];
  const arr = Array.isArray(v) ? v : [v];
  if (arr.length > 3 || arr.some((p) => typeof p !== 'string' || p.length > 64)) throw httpError(400, 'jobs.bad_passwords', 'At most three passwords of 64 characters.');
  // The driver types them on the console: a control character (the telnet escape above all) is no password
  if (arr.some((p) => CONTROL.test(p))) throw httpError(400, 'jobs.password_control', 'A password holds a control character.');
  return arr.filter((p) => p.length);
}

/** The RSA modulus an injection regenerates keys with, or null (the device's own choice) */
export function rsaModulusOf(body) {
  const raw = body?.rsaModulus;
  if (raw === undefined || raw === null || raw === '') return null;
  const modulus = Number(raw);
  if (!RSA_MODULI.includes(modulus)) throw httpError(400, 'jobs.bad_rsa', 'RSA keys: 512, 768, 1024, 2048 or 4096 bits.');
  return modulus;
}

/** A label typed by a person: trimmed, at most 80 characters */
export const labelOf = (v) => (typeof v === 'string' ? v.trim().slice(0, 80) : '');

/** Answer with a ZIP to download */
export function sendZip(res, data, filename) {
  res.set({
    'Cache-Control': 'no-store',
    'Content-Type': 'application/zip',
    'Content-Disposition': `attachment; filename="${filename.replace(/[^\w.-]/g, '_')}"`,
    'X-Content-Type-Options': 'nosniff',
  });
  res.end(Buffer.from(data));
}
