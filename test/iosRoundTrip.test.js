/**
 * Round trip on the simulator, the path a bench reset + injection takes:
 * configure a device as a group would, capture it (running-config and VLANs),
 * erase and reload it, replay the capture on the factory device, capture it
 * again: both captures must match, line for line, apart from the volatile
 * header comments.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { comparableConfig, toReplayScript } from '../src/lib/drivers/ciscoIos.js';
import { roundTrip, volatile } from './helpers/ios.js';

test('round trip: classic router (2811) with a banner, sub-interfaces, OSPF, DHCP and shut interfaces', { timeout: 30_000 }, async () => {
  const r = await roundTrip('2811', `configure terminal
hostname R1
enable secret class
service password-encryption
ip domain-name lab.local
no ip domain-lookup
username admin privilege 15 secret cisco
ip dhcp excluded-address 192.168.10.1 192.168.10.9
ip dhcp pool LAN10
 network 192.168.10.0 255.255.255.0
 default-router 192.168.10.1
interface Loopback0
 ip address 1.1.1.1 255.255.255.255
interface FastEthernet0/0
 no shutdown
interface FastEthernet0/0.10
 description VLAN 10 - etudiants
 encapsulation dot1Q 10
 ip address 192.168.10.1 255.255.255.0
interface FastEthernet0/1
 ip address 10.0.0.1 255.255.255.252
interface Serial0/0/0
 description Lien vers R2
 ip address 10.1.1.1 255.255.255.252
 clock rate 64000
 no shutdown
router ospf 1
 router-id 1.1.1.1
 network 10.1.1.0 0.0.0.3 area 0
ip route 0.0.0.0 0.0.0.0 10.1.1.2
banner motd #
Labo A - R1
! ne pas modifier
#
line con 0
 password cisco
 login
 logging synchronous
 exec-timeout 0 0
end
`, { secret: 'class' });
  assert.equal(volatile(r.after.config), volatile(r.before.config));
  assert.equal(comparableConfig(r.after.config), comparableConfig(r.before.config));
  assert.match(r.before.config, /^banner motd \^C\nLabo A - R1\n! ne pas modifier\n\^C$/m);
  assert.match(r.before.config, /^interface FastEthernet0\/1\n ip address 10\.0\.0\.1 255\.255\.255\.252\n shutdown/m, 'a shut interface stays shut');
  assert.match(r.after.config, /^ password 7 /m);
});

test('round trip: IOS XE router (ISR 4331) - certificate chain and licence regenerated by the device, not replayed', { timeout: 30_000 }, async () => {
  const r = await roundTrip('isr4331', `configure terminal
hostname R1
enable secret class
ip domain name tp.lab
interface GigabitEthernet0/0/0
 description Vers S1
 ip address 192.168.1.1 255.255.255.0
 no shutdown
interface GigabitEthernet0/0/2
 ip address 10.0.12.1 255.255.255.252
interface Loopback0
 ip address 2.2.2.2 255.255.255.255
router ospf 1
 router-id 2.2.2.2
 network 192.168.1.0 0.0.0.255 area 0
banner motd #R1 : labo#
line vty 0 4
 login local
 transport input ssh
end
`, { secret: 'class' });
  assert.equal(volatile(r.after.config), volatile(r.before.config));
  assert.match(r.before.config, /^crypto pki certificate chain /m);
  assert.ok(!/crypto pki|license udi|^platform/m.test(r.script));
  assert.ok(r.dropped.some((d) => d.text.startsWith('license udi')));
});

test('round trip: RSA keys generated on replay; IOS\'s "% The key modulus size…" lines are not errors', { timeout: 30_000 }, async () => {
  const r = await roundTrip('2811', `configure terminal
hostname R3
ip domain-name lab.local
line vty 0 4
 login local
 transport input ssh
end
`, { rsaModulus: 1024 });
  const l = r.script.trimEnd().split('\n');
  const at = l.indexOf('crypto key generate rsa general-keys modulus 1024');
  assert.equal(l[at - 1], 'ip domain-name lab.local');
  assert.deepEqual(toReplayScript(r.before.config, { facts: { kind: 'router' }, rsaModulus: 1024 }).lineTimeouts, { [at + 1]: 60_000 }, 'a longer budget for that line');
  assert.deepEqual(r.sent.errors, []);
  assert.equal(r.dev.rsaKeys, 1024);
  assert.equal(volatile(r.after.config), volatile(r.before.config));
});
