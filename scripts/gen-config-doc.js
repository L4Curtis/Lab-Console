// Builds docs/CONFIGURATION.md from .env.example, the single source of the
// configuration reference.  `npm run gen-config-doc` writes it; with --check
// it only compares (test/configDoc.test.js uses that).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '.env.example');
const target = join(root, 'docs', 'CONFIGURATION.md');

export function parseEnvExample(text) {
  const sections = [];
  let section = null;
  let notes = [];
  let afterVar = false;
  let shared = false;
  const flush = () => { notes = []; afterVar = false; shared = false; };
  for (const raw of text.split('\n')) {
    const line = raw.trimEnd();
    const head = /^# ── (.+?) ─+$/.exec(line);
    if (head) {
      section = { title: head[1], vars: [] };
      sections.push(section);
      flush();
      continue;
    }
    if (line === '' || /^# ─+$/.test(line)) { flush(); continue; }
    const variable = /^(# )?([A-Z][A-Z0-9_]+)=(.*)$/.exec(line);
    if (variable && section) {
      // A comment block describes the variables that follow it, up to the next block
      section.vars.push({
        name: variable[2],
        value: variable[3],
        optional: Boolean(variable[1]),
        note: shared ? 'Part of the group described in the row above.' : notes.join(' ').replace(/\s+/g, ' ').trim(),
      });
      if (notes.length) shared = true;
      afterVar = true;
      continue;
    }
    if (line.startsWith('#')) {
      if (afterVar) { notes = []; afterVar = false; shared = false; }
      notes.push(line.replace(/^#\s?/, ''));
    }
  }
  return sections.filter((s) => s.vars.length);
}

const cell = (text) => text.replace(/\|/g, '\\|');

export function renderConfigDoc(text) {
  const out = [
    '# Configuration reference',
    '',
    '**English** · the descriptions are those of `.env.example`; [README.fr.md](../README.fr.md) explains the main settings in French.',
    '',
    '> Generated from `.env.example` by `npm run gen-config-doc`. Do not edit this file:',
    '> change the comments in `.env.example` and generate it again.',
    '',
    'Settings are environment variables, read from `.env` (Docker Compose passes it',
    'to the container). A variable shown as *(optional)* is commented out in',
    '`.env.example`; the value is the default or an example. The jump server, console',
    'login and allowed consoles can also be changed from Administration > Lab',
    'parameters without a restart.',
    '',
  ];
  for (const { title, vars } of parseEnvExample(text)) {
    out.push(`## ${title}`, '', '| Variable | Default / example | Description |', '|---|---|---|');
    for (const v of vars) {
      const value = v.value === '' ? '*(empty)*' : `\`${cell(v.value)}\``;
      const tag = v.optional ? ' *(optional)*' : '';
      out.push(`| \`${v.name}\`${tag} | ${value} | ${cell(v.note)} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = renderConfigDoc(readFileSync(source, 'utf8'));
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (current !== doc) { console.error('docs/CONFIGURATION.md is out of date: npm run gen-config-doc'); process.exit(1); }
  } else {
    writeFileSync(target, doc);
    console.log('docs/CONFIGURATION.md written');
  }
}
